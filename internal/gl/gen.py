#!/usr/bin/env python3
"""Generates gl_desktop.go and gl_es.go.

The game imports "game/internal/gl" instead of a go-gl package directly. This
package re-exports, under the same names, the OpenGL functions and constants
the game uses: from OpenGL 3.3/4.1 core on desktops, and from OpenGL ES 3 on
Android. After using a new gl.Something in the game, run:

    python3 internal/gl/gen.py
"""
import glob, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
GOGL = "github.com/go-gl/gl"
BACKENDS = [
    ("gl_desktop.go", "!android", "v4.1-core/gl", "#version 330 core\\n", False),
    ("gl_es.go", "android", "v3.0/gles2", "#version 300 es\\nprecision highp float;\\nprecision highp int;\\n", True),
]
EXTRA = []  # names to export even though no game file uses them yet

def used_names():
    names = set(EXTRA)
    for path in glob.glob(os.path.join(ROOT, "*.go")):
        names |= set(re.findall(r"\bgl\.([A-Za-z_][A-Za-z0-9_]*)", open(path).read()))
    return sorted(names - {"IsES", "GLSLHead"})  # defined here, not re-exported

def module_dir():
    out = subprocess.run(["go", "list", "-m", "-f", "{{.Dir}}", GOGL], cwd=ROOT,
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()

def scan(pkgdir):
    funcs, consts = set(), {}
    for path in glob.glob(os.path.join(pkgdir, "*.go")):
        src = open(path).read()
        funcs |= set(re.findall(r"^func ([A-Z][A-Za-z0-9_]*)\(", src, re.M))
        for name, val in re.findall(r"^\t([A-Z][A-Z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", src, re.M):
            consts[name] = val
    return funcs, consts

def main():
    names = used_names()
    mod = module_dir()
    desktop_funcs, desktop_consts = scan(os.path.join(mod, "v4.1-core/gl"))
    for fname, tag, pkg, head, es in BACKENDS:
        funcs, consts = scan(os.path.join(mod, pkg))
        lines = [
            "// Code generated by gen.py; DO NOT EDIT.",
            "",
            f"//go:build {tag}",
            "",
            "package gl",
            "",
            f'import impl "{GOGL}/{pkg}"',
            "",
            f"// IsES is true when rendering through OpenGL ES (Android).",
            f"const IsES = {'true' if es else 'false'}",
            "",
            f"// GLSLHead starts every shader.",
            f'const GLSLHead = "{head}"',
            "",
        ]
        missing = []
        for n in names:
            if n in funcs:
                lines.append(f"var {n} = impl.{n}")
            elif n in consts:
                lines.append(f"const {n} = impl.{n}")
            elif n in desktop_consts:
                # desktop-only switch; the game skips it when IsES
                lines.append(f"const {n} = {desktop_consts[n]} // not in this API")
            else:
                missing.append(n)
        if missing:
            sys.exit(f"{pkg} has no {', '.join(missing)}")
        path = os.path.join(HERE, fname)
        open(path, "w").write("\n".join(lines) + "\n")
        subprocess.run(["gofmt", "-w", path], check=True)
        print("wrote", fname, len(names), "names")

main()
